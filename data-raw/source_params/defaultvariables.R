## code to prepare the default input values (`inst/extdata/defaultvariables.yaml`) goes here
## Default values of the input variables, which replace missing values in the
## input data (see prepare_dose_data()), from the columns "parameters" and
## "mean" of the tab "defaultvariables" of the parameter Excel file.

source("data-raw/source_params/reading_params_sources.R") # creates `params_copy` and `as_param()`

# Proportions of the urbanicity distribution (stochastic model): not input
# variables, so they get no default value. Every default value is added as a
# column to the input data.
urbanicity_props <- c("urb_prop", "sub_prop", "rur_prop")

rows <- readxl::read_excel(params_copy, sheet = "defaultvariables", col_types = "text")
rows <- rows[!is.na(rows$parameters) & !(rows$parameters %in% urbanicity_props),
             c("parameters", "mean")]

if (any(is.na(rows$mean))) {
  stop("Variable without a mean: ", paste(rows$parameters[is.na(rows$mean)], collapse = ", "))
}
if (anyDuplicated(rows$parameters)) {
  stop("Duplicated variable: ", paste(unique(rows$parameters[duplicated(rows$parameters)]), collapse = ", "))
}

# Mean as logical (TRUE/FALSE), number or text (e.g. country, urbanicity)
as_default <- function(mean) {
  number <- suppressWarnings(as.numeric(mean))
  if (toupper(mean) %in% c("TRUE", "FALSE")) {
    as.logical(toupper(mean))
  } else if (!is.na(number)) {
    as_param(number)
  } else {
    mean
  }
}
defaults <- stats::setNames(lapply(rows$mean, as_default), rows$parameters)

header <- c(
  "# Default values of the input variables, which replace missing values in the",
  "# input data (prepare_dose_data()).",
  "# Generated by data-raw/source_params/defaultvariables.R from the columns",
  "# \"parameters\" and \"mean\" of the tab \"defaultvariables\" of",
  "# params_sources.xlsx, do not edit by hand.")
# Logical values written as TRUE/FALSE (default of the yaml package: yes/no)
write_logical <- function(x) structure(ifelse(x, "TRUE", "FALSE"), class = "verbatim")
writeLines(
  c(header, sub("\n$", "", yaml::as.yaml(defaults, precision = 15,
                                         handlers = list(logical = write_logical)))),
  file.path("inst", "extdata", "defaultvariables.yaml"))
